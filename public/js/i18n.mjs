const DICTS = { fa, en };
let LANG = 'fa';
const missing = new Set();

export function setLang(l) {
  LANG = l === 'en' ? 'en' : 'fa';
  document.documentElement.lang = LANG;
  document.documentElement.dir = LANG === 'fa' ? 'rtl' : 'ltr';
}
export const lang = () => LANG;
export const isFa = () => LANG === 'fa';

export function t(key, params) {
  const dict = DICTS[LANG] || fa;
  
  // Apply dynamic overrides from admin settings if exist
  const overrides = window._translationsOverride || window.__SEED?.settings?.translations || {};
  let s = overrides[LANG]?.[key];

  if (s === undefined) s = dict[key];
  if (s === undefined) {
    
    s = overrides['fa']?.[key]; // fallback to dynamic fa
    if (s === undefined) s = fa[key]; // fallback to static fa
    if (s === undefined) {
      if (!missing.has(key)) {
        missing.add(key);
        if (location.hostname === 'localhost' || location.hostname === '127.0.0.1') console.warn('[i18n] missing key:', key);
      }
      s = key;
    }
  }
  if (params) for (const [k, v] of Object.entries(params)) s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
  return s;
}

/** ترجمه‌ی المان‌هایی با data-i18n */
export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((n) => { n.textContent = t(n.dataset.i18n); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((n) => { n.setAttribute('placeholder', t(n.dataset.i18nPlaceholder)); });
  root.querySelectorAll('[data-i18n-title]').forEach((n) => { n.setAttribute('title', t(n.dataset.i18nTitle)); n.setAttribute('aria-label', t(n.dataset.i18nTitle)); });
  root.querySelectorAll('[data-i18n-html]').forEach((n) => { n.innerHTML = t(n.dataset.i18nHtml); });
}

export const missingKeys = () => [...missing];
export const dictSize = () => ({ fa: Object.keys(fa).length, en: Object.keys(en).length });

