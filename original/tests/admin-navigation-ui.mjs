import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
const dom = new JSDOM('<!doctype html><html><body><main id="testRoot"></main></body></html>', { url: 'http://test.local/#/admin/layout/adminNav' });
for (const key of ['window', 'document', 'Element', 'HTMLElement', 'Event', 'CustomEvent', 'FormData', 'location', 'history', 'localStorage', 'sessionStorage', 'navigator', 'MutationObserver']) {
  Object.defineProperty(globalThis, key, { value: dom.window[key], configurable: true });
}
globalThis.matchMedia = () => ({ matches: false, addEventListener() {}, removeEventListener() {} });
globalThis.requestAnimationFrame = fn => setTimeout(fn, 0);
globalThis.getComputedStyle = dom.window.getComputedStyle.bind(dom.window);
const { S } = await import('../public/js/state.mjs');
const { api } = await import('../public/js/lib/api.mjs');
const { getAct } = await import('../public/js/actions.mjs');
const { setLang } = await import('../public/js/i18n.mjs');
const { SECTIONS, render, allowedSections } = await import('../public/js/views/admin/index.mjs');
const { renderAdminNav } = await import('../public/js/views/admin/admin-nav.mjs');
const settingsView = await import('../public/js/views/admin/settings.mjs');
const { normalizeAdminNav } = await import('../public/js/lib/admin-nav.mjs');
const root = document.querySelector('#testRoot');
let config = { features: {}, adminNav: normalizeAdminNav() };
let saved;
S.me = { role: 'owner', permissions: {} }; S.settings = config;
api.get = async path => path === '/api/admin/settings' || path === '/api/bootstrap' ? { settings: config } : { counts: { pending: 2 } };
api.patch = async (path, body) => {
  saved = { path, value: structuredClone(body.value) };
  config.adminNav = normalizeAdminNav(body.value);
  return { value: config.adminNav };
};
root.innerHTML = await renderAdminNav();
assert.equal(root.querySelectorAll('[data-admin-nav-row]').length, SECTIONS.length);
assert.equal(root.querySelector('[name=en]').dir, 'ltr');
assert.equal(root.querySelector('[name=fa]').maxLength, 80);
const row = root.querySelector('[data-id="products"]');
row.querySelector('[name=fa]').value = 'قطعات';
row.querySelector('[name=en]').value = 'Parts';
row.querySelector('[name=icon]').value = 'users';
row.querySelector('[name=show]').checked = false;
getAct('admin-nav-move')({}, row.querySelector('[data-direction=up]'));
assert.equal(root.querySelector('[data-admin-nav-row]'), row);
assert.equal(row.querySelector('[name=fa]').value, 'قطعات', 'moving must retain edits');
getAct('admin-nav-move')({}, row.querySelector('[data-direction=up]'));
assert.equal(root.querySelector('[data-admin-nav-row]'), row, 'first item stays first');
getAct('admin-nav-move')({}, row.querySelector('[data-direction=down]'));
assert.equal(root.querySelectorAll('[data-admin-nav-row]')[1], row);
getAct('admin-nav-move')({}, row.querySelector('[data-direction=up]'));
await getAct('admin-nav-save')({ preventDefault() {} }, root.querySelector('form'));
assert.equal(saved.path, '/api/admin/settings/adminNav');
assert.equal(saved.value.order[0], 'products');
assert.ok(saved.value.hidden.includes('products'));
assert.deepEqual(saved.value.customLabels.products, { fa: 'قطعات', en: 'Parts' });
assert.equal(saved.value.customIcons.products, 'users');

const ctx = { params: { section: 'layout', id: 'adminNav' }, query: new URLSearchParams() };
config.adminNav = normalizeAdminNav({ order: ['chat', 'products', '', 'layout'], hidden: ['layout'], customLabels: { chat: { fa: 'تیم', en: 'Team' }, products: { fa: '\u0001<img src=x onerror=alert(1)>\u0002' } }, customIcons: { chat: 'users', products: '\" onload=alert(1)' } });
S.settings = config;
root.innerHTML = await render(ctx);
assert.deepEqual([...root.querySelectorAll('.adm-side a')].slice(0, 3).map(a => a.hash), ['#/admin/chat', '#/admin/products', '#/admin']);
assert.equal(root.querySelector('.adm-side a span').textContent, 'تیم');
assert.equal(root.querySelector('.adm-side use').getAttribute('href'), '#i-users');
assert.ok(!root.querySelector('.adm-side img'), 'custom labels cannot inject HTML');
assert.ok(root.querySelector('.adm-side').textContent.includes('<img'));
assert.ok(!root.querySelector('.adm-side a[href="#/admin/layout"]'));
assert.ok(root.querySelector('a[href="#/admin/layout/adminNav"]'), 'editor recovery link survives hiding layout');
assert.ok(root.querySelector('[data-admin-nav-row]'), 'hidden layout route remains accessible');
setLang('en'); root.innerHTML = await render(ctx);
assert.equal(root.querySelector('.adm-side a span').textContent, 'Team');
config.adminNav = normalizeAdminNav({ hidden: SECTIONS.map(s => s.id) });
root.innerHTML = await render(ctx);
assert.equal(root.querySelectorAll('.adm-side a').length, 0);
assert.ok(root.querySelector('a[href="#/admin/layout/adminNav"]'));
S.me = { role: 'staff', permissions: { 'products.view': true } };
config.adminNav = normalizeAdminNav({ order: ['settings', 'products'] });
root.innerHTML = await render(ctx);
assert.ok(!root.querySelector('[data-admin-nav-row]'));
assert.ok(!root.querySelector('.adm-side a[href="#/admin/settings"]'));
assert.ok(allowedSections().some(s => s.id === 'products'));
S.me = { role: 'owner' }; config.features.adminChat = false;
root.innerHTML = await render(ctx);
assert.ok(!root.querySelector('.adm-side a[href="#/admin/chat"]'));
assert.ok(root.querySelector('[data-admin-nav-row][data-id="chat"]'), 'feature-disabled items still editable');
root.innerHTML = await settingsView.render({ params: { section: 'settings', id: 'products' } });
assert.equal(root.querySelector('[name=lowStockTelegramAlertEnabled]').checked, false);
const threshold = root.querySelector('[name=lowStockTelegramAlertThreshold]');
assert.equal(threshold.value, '3'); assert.equal(threshold.min, '1'); assert.equal(threshold.max, '100000');
root.innerHTML = await settingsView.render({ params: { section: 'settings', id: 'team' } });
assert.equal(root.querySelector('[name="features.adminChat"]').checked, false);
console.log('✔ admin-navigation-ui: all rows, DOM moves, saved fields, global order, both languages, XSS, hidden routes, recovery and permissions');
dom.window.close();
